"""Embeds PyVis HTML in Streamlit and draws colour legends.

The HTML is generated by kg.viz, which escapes every value coming from the database or the AI
before it reaches a tooltip, so it is safe to embed in the app's iframe.
"""
from __future__ import annotations

import html as _html

import streamlit as st

from components import viz


def show_html(html: str, height: int = 620) -> None:
    if hasattr(st, "iframe"):                 # Streamlit >= 1.5x
        st.iframe(html, height=height + 20)
    else:                                     # older Streamlit
        import streamlit.components.v1 as components
        components.html(html, height=height + 20, scrolling=False)


def legend(labels) -> None:
    cmap = viz.color_map(labels)
    chips = "".join(f'<span class="kg-chip" style="background:{c};color:#fff">{_html.escape(l)}</span>'
                    for l, c in cmap.items())
    st.markdown(chips, unsafe_allow_html=True)


def show_graph(G, height: int = 620, hide: set[str] | None = None, highlight: set[str] | None = None) -> None:
    if G.number_of_nodes() == 0:
        st.info("The graph is empty.")
        return
    legend(d.get("label", "?") for _, d in G.nodes(data=True))
    show_html(viz.graph_html(G, f"{height}px", hide=hide, highlight=highlight), height)


def show_ontology(onto, height: int = 460) -> None:
    show_html(viz.ontology_html(onto, f"{height}px"), height)
    st.caption("Boxes = classes (node types) with their source table · arrows = relationship types · "
               "dashed arrows came from the AI.")
