BEGIN;

CREATE TABLE IF NOT EXISTS kg_meta.app_user (
    username text PRIMARY KEY,
    password_hash text NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS kg_meta.graph_project (
    project_id uuid PRIMARY KEY,
    owner_name text NOT NULL,
    name text NOT NULL,
    current_build_id text REFERENCES kg_meta.graph_build(build_id)
);

CREATE TABLE IF NOT EXISTS kg_meta.graph_project_member (
    project_id uuid NOT NULL REFERENCES kg_meta.graph_project(project_id),
    username text NOT NULL REFERENCES kg_meta.app_user(username),
    role text NOT NULL CHECK (role = 'viewer'),
    PRIMARY KEY (project_id, username)
);

ALTER TABLE kg_meta.graph_build
    ADD COLUMN IF NOT EXISTS project_id uuid REFERENCES kg_meta.graph_project(project_id),
    ADD COLUMN IF NOT EXISTS actor text,
    ADD COLUMN IF NOT EXISTS source_id text,
    ADD COLUMN IF NOT EXISTS rejected_count integer,
    ADD COLUMN IF NOT EXISTS error_code text,
    ADD COLUMN IF NOT EXISTS analytics jsonb;

CREATE INDEX IF NOT EXISTS ix_graph_build_project
    ON kg_meta.graph_build(project_id, started_at DESC);

CREATE TABLE IF NOT EXISTS kg_meta.graph_version_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id uuid NOT NULL REFERENCES kg_meta.graph_project(project_id),
    build_id text NOT NULL REFERENCES kg_meta.graph_build(build_id),
    action text NOT NULL,
    actor text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kg_meta.graph_workspace_item (
    project_id uuid NOT NULL REFERENCES kg_meta.graph_project(project_id),
    build_id text NOT NULL REFERENCES kg_meta.graph_build(build_id),
    actor text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('scene', 'query', 'query_run')),
    name text NOT NULL,
    settings jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, build_id, actor, kind, name)
);

COMMIT;
